/**
 * Odyssey Edge Tunnel worker — the panel's own VPN backend running ON
 * Cloudflare Workers (no VPS needed). This is what makes generated configs
 * actually connect and why they are fast: traffic terminates on the nearest
 * Cloudflare edge instead of one central server.
 *
 * Protocols, dispatched by WebSocket path (all under the panel-generated
 * secret path, e.g. /<PATH_SECRET>/vless):
 *   .../vless  → VLESS over WebSocket   (uuid auth — public vless spec)
 *   .../trojan → Trojan over WebSocket  (sha224 password — public trojan spec)
 *   .../ss     → Shadowsocks AES-256-GCM over WebSocket (v2ray-plugin
 *               "mode=websocket" pass-through; AEAD per the public
 *               shadowsocks.org specification)
 *
 * Security model:
 *   - the secret path (generated per deployment by the panel) gates access
 *   - Shadowsocks is additionally password-protected by its own crypto — a
 *     wrong password simply fails to decrypt, so no allow-list is needed
 *   - VLESS/Trojan accept any matching-format credential; the panel can
 *     optionally lock them down with the TUNNEL_ALLOW env (comma-separated
 *     uuid/password list)
 *
 * Written from scratch for Odyssey against the public protocol specs.
 */

const VERSION = 'odyssey-tunnel/2.1.0'

const PROTO_VLESS = 'vless'
const PROTO_TROJAN = 'trojan'
const PROTO_SS = 'ss'

type Env = {
  PATH_SECRET?: string
  TUNNEL_ALLOW?: string
  TUNNEL_PROXYIP?: string
}

export function tunnelWorkerSource(proxyIp = ''): string {
  return [
    "// Odyssey Edge Tunnel v2 — VLESS + Trojan + Shadowsocks over WebSocket",
    "// Deployed automatically by the Odyssey panel. Cloudflare Workers (free plan OK).",
    "import { connect } from 'cloudflare:sockets';",
    '',
    `const VERSION = '${VERSION}';`,
    `const PROXY_IP_DEFAULT = '${proxyIp}';`,
    '',
    "export default {",
    "  async fetch(request, env) {",
    "    const url = new URL(request.url);",
    "    if ((request.headers.get('Upgrade') || '').toLowerCase() === 'websocket') {",
    "      const route = resolveRoute(url, env);",
    "      if (!route) return new Response('Not found', { status: 404 });",
    "      const pair = new WebSocketPair();",
    "      const server = pair[1];",
    "      server.accept();",
    "      const early = url.searchParams.get('ed') || '';",
    "      route(server, early, env).catch(() => safeClose(server));",
    "      return new Response(null, { status: 101, webSocket: pair[0] });",
    "    }",
    "    if (url.pathname === '/health') {",
    "      return json({ ok: true, version: VERSION, protocols: ['vless', 'trojan', 'shadowsocks'] });",
    "    }",
    "    return json({ ok: true, version: VERSION, service: 'odyssey-tunnel' });",
    "  },",
    "};",
    '',
    "function json(obj) {",
    "  return new Response(JSON.stringify(obj), {",
    "    headers: { 'content-type': 'application/json; charset=utf-8',",
    "      'access-control-allow-origin': '*' },",
    "  });",
    "}",
    '',
    "function safeClose(ws) { try { ws.close(); } catch (_) {} }",
    '',
    "// /<secret>[/<proto>] → protocol handler; bare secret = vless (legacy)",
    "function resolveRoute(url, env) {",
    "  const secret = (env.PATH_SECRET || '').replace(/^\\/+|\\/+$/g, '');",
    "  const seg = url.pathname.replace(/^\\/+|\\/+$/g, '');",
    "  if (!secret || !seg) return null;",
    "  const parts = seg.split('/');",
    "  if (parts[0] !== secret) return null;",
    "  const proto = (parts[1] || 'vless').toLowerCase();",
    "  if (proto === 'trojan') return serveTrojan;",
    "  if (proto === 'ss' || proto === 'shadowsocks') return serveShadowsocks;",
    "  return serveVless;",
    "}",
    '',
    "function allowed(secret, env) {",
    "  const list = (env.TUNNEL_ALLOW || '').trim();",
    "  if (!list) return true; // open tunnel — the secret path gates access",
    "  return list.split(',').map(s => s.trim()).includes(secret);",
    "}",
    '',
    "// ── shared socket pump ───────────────────────────────────────────────",
    '',
    "function pumpTcp(ws, sock) {",
    "  (async () => {",
    "    const reader = sock.readable.getReader();",
    "    for (;;) {",
    "      const { done, value } = await reader.read();",
    "      if (done) return safeClose(ws);",
    "      if (value && value.byteLength) ws.send(value);",
    "    }",
    "  })().catch(() => safeClose(ws));",
    "  ws.addEventListener('close', () => { try { sock.close(); } catch (_) {} });",
    "  ws.addEventListener('error', () => { try { sock.close(); } catch (_) {} });",
    "}",
    '',
    "async function toBytes(data) {",
    "  if (data instanceof ArrayBuffer) return new Uint8Array(data);",
    "  if (data instanceof Uint8Array) return data;",
    "  return new Uint8Array(await new Response(data).arrayBuffer());",
    "}",
    '',
    "// atype 1 = ipv4, 2 = domain, 3 = ipv6 → { host, port, rest }",
    "function parseTarget(atype, data, off) {",
    "  if (atype === 1 && data.byteLength >= off + 6) {",
    "    const ip = Array.from(data.slice(off, off + 4)).join('.');",
    "    return { host: ip, port: (data[off + 4] << 8) | data[off + 5], rest: data.slice(off + 6) };",
    "  }",
    "  if (atype === 2 && data.byteLength > off + 1) {",
    "    const len = data[off];",
    "    const host = new TextDecoder().decode(data.slice(off + 1, off + 1 + len));",
    "    const p = off + 1 + len;",
    "    return { host, port: (data[p] << 8) | data[p + 1], rest: data.slice(p + 2) };",
    "  }",
    "  if (atype === 3 && data.byteLength >= off + 18) {",
    "    const parts = [];",
    "    for (let i = 0; i < 16; i += 2) parts.push(((data[off + i] << 8) | data[off + i + 1]).toString(16));",
    "    const host = parts.join(':');",
    "    const p = off + 16;",
    "    return { host, port: (data[p] << 8) | data[p + 1], rest: data.slice(p + 2) };",
    "  }",
    "  return null;",
    "}",
    '',
    "function dial(env, host, port) {",
    "  // TUNNEL_PROXYIP accepts a single relay or a comma-separated pool;",
    "  // one entry is picked per connection to spread the load.",
    "  const raw = (env.TUNNEL_PROXYIP || PROXY_IP_DEFAULT || '').trim();",
    "  const pool = raw.split(',').map(s => s.trim()).filter(Boolean);",
    "  if (pool.length) {",
    "    const pick = pool[Math.floor(Math.random() * pool.length)];",
    "    return connect(pick.includes(':') ? pick : pick + ':443', { allowUntrusted: false });",
    "  }",
    "  return connect(host + ':' + port, { allowUntrusted: false });",
    "}",
    '',
    "// ── VLESS over WebSocket ─────────────────────────────────────────────",
    '',
    "async function serveVless(ws, early, env) {",
    "  let writer = null;",
    "  let headerSeen = false;",
    "  const earlyBytes = early ? await toBytes(early) : null;",
    "  ws.addEventListener('message', async (event) => {",
    "    try {",
    "      const data = await toBytes(event.data);",
    "      if (headerSeen) {",
    "        if (writer && data.byteLength) await writer.write(data);",
    "        return;",
    "      }",
    "      let msg = data;",
    "      if (earlyBytes && earlyBytes.byteLength && data.byteLength < 26) {",
    "        const merged = new Uint8Array(earlyBytes.byteLength + data.byteLength);",
    "        merged.set(earlyBytes, 0); merged.set(data, earlyBytes.byteLength);",
    "        msg = merged;",
    "      }",
    "      if (msg.byteLength < 26) return;",
    "      const uid = [...msg.slice(1, 17)].map(b => b.toString(16).padStart(2, '0')).join('');",
    "      if (!allowed(uid, env)) return safeClose(ws);",
    "      const addonsLen = msg[17];",
    "      const opt = 18 + addonsLen;",
    "      const cmd = msg[opt];",
    "      const port = (msg[opt + 1] << 8) | msg[opt + 2];",
    "      const t = parseTarget(msg[opt + 3], msg, opt + 4);",
    "      ws.send(new Uint8Array([msg[0], 0]).buffer); // vless ack",
    "      if (!t || cmd !== 1) return; // TCP connect commands only",
    "      const sock = dial(env, t.host, t.port);",
    "      writer = sock.writable.getWriter();",
    "      if (t.rest.byteLength) await writer.write(t.rest);",
    "      headerSeen = true;",
    "      pumpTcp(ws, sock);",
    "    } catch (_) { safeClose(ws); }",
    "  });",
    "}",
    '',
    "// ── Trojan over WebSocket (sha224(password) hex + CRLF + addr + CRLF) ─",
    '',
    "async function serveTrojan(ws, _early, env) {",
    "  let writer = null;",
    "  let headerSeen = false;",
    "  ws.addEventListener('message', async (event) => {",
    "    try {",
    "      const data = await toBytes(event.data);",
    "      if (headerSeen) {",
    "        if (writer && data.byteLength) await writer.write(data);",
    "        return;",
    "      }",
    "      if (data.byteLength < 60) return safeClose(ws);",
    "      const hex = new TextDecoder().decode(data.slice(0, 56));",
    "      if (!/^[0-9a-fA-F]{56}$/.test(hex)) return safeClose(ws);",
    "      if (!allowed(hex, env)) return safeClose(ws);",
    "      if (data[56] !== 13 || data[57] !== 10) return safeClose(ws);",
    "      const cmd = data[58];",
    "      const t = parseTarget(data[59], data, 60);",
    "      if (!t || cmd !== 1) return safeClose(ws);",
    "      const sock = dial(env, t.host, t.port);",
    "      writer = sock.writable.getWriter();",
    "      if (t.rest.byteLength) await writer.write(t.rest);",
    "      headerSeen = true;",
    "      pumpTcp(ws, sock);",
    "    } catch (_) { safeClose(ws); }",
    "  });",
    "}",
    '',
    "// ── Shadowsocks AES-256-GCM over WebSocket (v2ray-plugin ws mode) ────",
    "const SS_SALT = 32, SS_TAG = 16, SS_IVLEN = 12;",
    '',
    "async function serveShadowsocks(ws, _early, env) {",
    "  let dec = null;",
    "  let writer = null;",
    "  let opened = false;",
    "  ws.addEventListener('message', async (event) => {",
    "    try {",
    "      const data = await toBytes(event.data);",
    "      if (!dec) {",
    "        const st = await ssHandshake(data, ws, env);",
    "        if (!st) return safeClose(ws);",
    "        dec = st.dec;",
    "        writer = st.writer;",
    "        opened = true; // server→client pump lives inside ssHandshake",
    "        return;",
    "      }",
    "      // consume [len+tag][payload+tag] chunks from the client stream",
    "      await consumeSsChunks(dec, data, writer);",
    "    } catch (_) { safeClose(ws); }",
    "  });",
    "  ws.addEventListener('close', () => { if (!opened) safeClose(ws); });",
    "}",
    '',
    "async function ssHandshake(data, ws, env) {",
    "  if (data.byteLength < SS_SALT + 2 + SS_TAG + 2 + SS_TAG) return null;",
    "  const pass = (env.TUNNEL_SS_PASSWORD || env.PATH_SECRET || '').trim();",
    "  const key = await evpBytesToKey(pass, 32);",
    "  const salt = data.slice(0, SS_SALT);",
    "  const dec = await aead(await hkdfSha1(key, salt, 'ss-subkey', 32));",
    "  const lenPlain = await dec.open(data.slice(SS_SALT, SS_SALT + 2 + SS_TAG));",
    "  const len = (lenPlain[0] << 8) | lenPlain[1];",
    "  if (len < 1 || len > 16383) return null;",
    "  const b0 = SS_SALT + 2 + SS_TAG;",
    "  if (data.byteLength < b0 + len + SS_TAG) return null;",
    "  const body = await dec.open(data.slice(b0, b0 + len + SS_TAG));",
    "  const t = parseTarget(body[0], body, 1);",
    "  if (!t) return null;",
    "  const sock = dial(env, t.host, t.port);",
    "  const writer = sock.writable.getWriter();",
    "  if (t.rest.byteLength) await writer.write(t.rest);",
    "  // our downstream stream: fresh salt + subkey, AEAD-framed per chunk",
    "  const encSalt = crypto.getRandomValues(new Uint8Array(SS_SALT));",
    "  const enc = await aead(await hkdfSha1(key, encSalt, 'ss-subkey', 32));",
    "  ws.send(encSalt.buffer);",
    "  // pump server→client through the SS AEAD framing",
    "  (async () => {",
    "    const reader = sock.readable.getReader();",
    "    for (;;) {",
    "      const { done, value } = await reader.read();",
    "      if (done) return safeClose(ws);",
    "      if (value && value.byteLength) {",
    "        const frame = await enc.seal(value);",
    "        ws.send(frame.buffer);",
    "      }",
    "    }",
    "  })().catch(() => safeClose(ws));",
    "  ws.addEventListener('close', () => { try { sock.close(); } catch (_) {} });",
    "  ws.addEventListener('error', () => { try { sock.close(); } catch (_) {} });",
    "  return { dec, writer, sock };",
    "}",
    '',
    "async function consumeSsChunks(dec, chunk, writer) {",
    "  let off = 0;",
    "  while (off + 2 + SS_TAG <= chunk.byteLength) {",
    "    const lp = await dec.open(chunk.slice(off, off + 2 + SS_TAG));",
    "    const l = (lp[0] << 8) | lp[1];",
    "    if (l < 1 || l > 16383) throw new Error('bad chunk');",
    "    const s = off + 2 + SS_TAG, e = s + l + SS_TAG;",
    "    if (chunk.byteLength < e) return; // wait for the rest",
    "    const payload = await dec.open(chunk.slice(s, e));",
    "    if (payload.byteLength && writer) await writer.write(payload);",
    "    off = e;",
    "  }",
    "}",
    '',
    "async function aead(key) {",
    "  const k = await crypto.subtle.importKey('raw', key, 'AES-GCM', false, ['encrypt', 'decrypt']);",
    "  let n = 0;",
    "  const nonce = () => {",
    "    const iv = new Uint8Array(SS_IVLEN);",
    "    const v = n++;",
    "    iv[8] = (v >>> 24) & 255; iv[9] = (v >>> 16) & 255; iv[10] = (v >>> 8) & 255; iv[11] = v & 255;",
    "    return iv;",
    "  };",
    "  return {",
    "    async open(bytes) {",
    "      const L = bytes.byteLength - SS_TAG;",
    "      const out = await crypto.subtle.decrypt({ name: 'AES-GCM', iv: nonce() }, k, bytes.slice(0, L));",
    "      return new Uint8Array(out);",
    "    },",
    "    async seal(payload) {",
    "      const l = payload.byteLength;",
    "      const lenPlain = new Uint8Array([(l >> 8) & 255, l & 255]);",
    "      const ct = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv: nonce() }, k, lenPlain));",
    "      const body = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv: nonce() }, k, payload));",
    "      const out = new Uint8Array(ct.byteLength + body.byteLength);",
    "      out.set(ct, 0); out.set(body, ct.byteLength);",
    "      return out;",
    "    },",
    "  };",
    "}",
    '',
    "async function hkdfSha1(key, salt, info, bits) {",
    "  const base = await crypto.subtle.importKey('raw', key, 'HKDF', false, ['deriveBits']);",
    "  const d = await crypto.subtle.deriveBits(",
    "    { name: 'HKDF', hash: 'SHA-1', salt, info: new TextEncoder().encode(info) }, base, bits * 8);",
    "  return new Uint8Array(d);",
    "}",
    '',
    "// OpenSSL-style EVP_BytesToKey (MD5) — the standard Shadowsocks password KDF.",
    "async function evpBytesToKey(password, keyLen) {",
    "  const pw = new TextEncoder().encode(password);",
    "  const chunks = [];",
    "  let prev = new Uint8Array(0);",
    "  let total = 0;",
    "  while (total < keyLen) {",
    "    const input = new Uint8Array(prev.byteLength + pw.byteLength);",
    "    input.set(prev, 0); input.set(pw, prev.byteLength);",
    "    const dig = new Uint8Array(await crypto.subtle.digest('MD5', input));",
    "    chunks.push(dig); total += dig.byteLength; prev = dig;",
    "  }",
    "  const out = new Uint8Array(keyLen);",
    "  let off = 0;",
    "  for (const c of chunks) {",
    "    const take = Math.min(c.byteLength, keyLen - off);",
    "    out.set(c.slice(0, take), off); off += take;",
    "    if (off >= keyLen) break;",
    "  }",
    "  return out;",
    "}",
  ].join('\n')
}
