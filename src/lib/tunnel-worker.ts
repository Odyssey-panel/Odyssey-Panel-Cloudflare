/**
 * Odyssey Edge Tunnel worker — the panel's own VPN backend running ON
 * Cloudflare Workers (no VPS needed). This is what makes generated configs
 * actually connect and why they are fast: traffic terminates on the nearest
 * Cloudflare edge instead of one central server.
 *
 * Protocols, dispatched by WebSocket path (all under the panel-generated
 * secret path, e.g. /<PATH_SECRET>/vless):
 *   .../vless  → VLESS over WebSocket   (uuid auth — public vless spec)
 *   .../trojan → Trojan over WebSocket  (sha224 password — public trojan spec)
 *   .../ss     → Shadowsocks AES-256-GCM over WebSocket (v2ray-plugin
 *               "mode=websocket" pass-through; AEAD per the public
 *               shadowsocks.org specification)
 *
 * Routing (v3 — "smart dial", write-first, 0-RTT):
 *   Every target is dialed DIRECTLY from the edge first — one hop, the
 *   fastest possible path. The first payload (e.g. the TLS ClientHello) is
 *   written into the socket the moment it is created, without waiting for
 *   the TCP open round trip; only when the direct socket cannot open (the
 *   classic case: the target site is itself behind Cloudflare, and Workers
 *   are not allowed to connect to Cloudflare's own network) the connection
 *   is retried through the configured proxy-IP relay pool.
 *   0-RTT early data (v2ray "?ed=" convention) is honoured: clients send the
 *   first payload base64url-encoded in the sec-websocket-protocol header,
 *   saving a full round trip per connection.
 *   VLESS command 2 (UDP) is answered for DNS (port 53) via DoH — clients
 *   that resolve through the proxy keep working; other UDP ports close.
 *
 * Content policy (optional, baked at deploy time):
 *   TUNNEL_BLOCK = "ads", "porn" or "ads,porn" → target domains are checked
 *   against compact blocklists before any socket is opened.
 *
 * Security model:
 *   - the secret path (generated per deployment by the panel) gates access
 *   - Shadowsocks is additionally password-protected by its own crypto — a
 *     wrong password simply fails to decrypt, so no allow-list is needed
 *   - VLESS/Trojan accept any matching-format credential; the panel can
 *     optionally lock them down with the TUNNEL_ALLOW env (comma-separated
 *     uuid/password list)
 *
 * v3.0.0 changelog (the "ping OK, zero traffic" release):
 *   - FIX: hostPort() was referenced by every dial but never defined in the
 *     generated source — each connection died with a swallowed
 *     ReferenceError before any socket was opened. The single root cause of
 *     "configs ping but nothing opens".
 *   - FIX: Shadowsocks EVP_BytesToKey used crypto.subtle.digest('MD5'),
 *     which Workers' WebCrypto does not support → pure-JS MD5 now.
 *   - FIX: Shadowsocks chunks split across WebSocket messages are carried
 *     over (proper len/payload state machine) instead of dropped.
 *   - FIX: Shadowsocks AEAD open() sliced off the 16-byte GCM tag — WebCrypto
 *     requires ciphertext||tag, so every verification failed.
 *   - FIX: early data now comes from sec-websocket-protocol (the v2ray "ed"
 *     convention) — the old code mistakenly used the ?ed= value itself.
 *   - SPEED: first payload is written before awaiting socket.opened (saves
 *     one RTT per connection), the 50ms drain sleep on close is gone.
 *
 * Written from scratch for Odyssey against the public protocol specs.
 */

